import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { smokeElectron } from '../../scripts/smoke-electron.mjs';
const target=path.resolve('evidence/RECEIPT-S06-R1');
const data=mkdtempSync(path.join(tmpdir(),'BookKeepAI S06 receipt startup '));
process.env.LOCALAPPDATA=data;
const result=await smokeElectron({reportPath:path.join(target,'selftest-dev.json'),restartReportPath:path.join(target,'selftest-dev-restart.json')});
writeFileSync(path.join(target,'startup-result.json'),JSON.stringify({localAppData:data,...result},null,2)+'\n','utf8');
process.exitCode=result.ok?0:1;
